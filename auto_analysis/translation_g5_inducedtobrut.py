SIZES = [1, 2, 6, 21]
MATRICES = [MATRIX_2n, MATRIX_3n, MATRIX_4n, MATRIX]

def apply_matrices(counts):
    assert len(counts) == 30, f"Attendu 30 valeurs, reçu {len(counts)}"
    result = []
    idx = 0
    for size, M in zip(SIZES, MATRICES):
        block = np.array(counts[idx:idx+size])
        result.extend((M @ block).tolist())
        idx += size
    return result


input_json = sys.argv[1]
output_json = sys.argv[2]

with open(input_json) as f:
    data = json.load(f)

results = {}
for key, counts in data.items():
    results[key] = apply_matrices(counts)

with open(output_json, "w") as f:
    json.dump(results, f, indent=2)

print("Done.")